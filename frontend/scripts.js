function translateEntireDOM(targetLang) {
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName.toLowerCase();
        if (['script', 'style', 'svg', 'path', 'noscript'].includes(tag)) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  let textNode;
  while ((textNode = walker.nextNode())) {
    if (!textNode._originalText) {
      textNode._originalText = textNode.nodeValue;
    }

    if (targetLang === 'ua') {
      const trimmed = textNode._originalText.trim();
      if (SITE_TRANSLATIONS[trimmed]) {
        textNode.nodeValue = textNode._originalText.replace(trimmed, SITE_TRANSLATIONS[trimmed]);
      }
    } else {
      textNode.nodeValue = textNode._originalText;
    }
  }

  document.querySelectorAll('input, textarea').forEach(input => {
    if (!input._origPlaceholder && input.placeholder) {
      input._origPlaceholder = input.placeholder;
    }
    if (input._origPlaceholder) {
      const trimmedPH = input._origPlaceholder.trim();
      if (targetLang === 'ua' && SITE_TRANSLATIONS[trimmedPH]) {
        input.placeholder = SITE_TRANSLATIONS[trimmedPH];
      } else if (targetLang === 'en') {
        input.placeholder = input._origPlaceholder;
      }
    }
  });
}

