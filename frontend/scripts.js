    if (track && slides.length > 0 && sliderContainer) {
        const visibleSlides = Math.min(4, slides.length);
        const totalSlides = slides.length;
        const slideDuration = 5000;

        let currentIndex = 0;
        let autoplayTimer = null;
        let isTransitioning = false;

        for (let i = 0; i < visibleSlides; i++) {
            const clone = slides[i].cloneNode(true);
            clone.classList.add('clone');
            track.appendChild(clone);
        }

        const getStepWidth = () => {
            const firstSlide = slides[0];
            if (!firstSlide) return 0;
            const slideWidth = firstSlide.getBoundingClientRect().width;
            const computedStyle = window.getComputedStyle(track);
            const gap = parseFloat(computedStyle.gap) || 0;
            return slideWidth + gap;
        };

        const updateDots = () => {
            if (!dots.length) return;
            const activeDotIndex = ((currentIndex % totalSlides) + totalSlides) % totalSlides;
            dots.forEach((dot, index) => {
                dot.classList.toggle('active', index === activeDotIndex);
            });
        };

        const goToSlide = (index, animate = true) => {
            const stepWidth = getStepWidth();
            if (!stepWidth) return;
            track.style.transition = animate ? 'transform 0.5s cubic-bezier(0.25, 1, 0.5, 1)' : 'none';
            currentIndex = index;
            track.style.transform = `translateX(-${currentIndex * stepWidth}px)`;
            updateDots();
        };

        const nextSlide = () => {
            if (isTransitioning) return;
            goToSlide(currentIndex + 1, true);
        };

        const prevSlide = () => {
            if (isTransitioning) return;
            if (currentIndex <= 0) {
                goToSlide(totalSlides, false);
                void track.offsetHeight;
                goToSlide(totalSlides - 1, true);
            } else {
                goToSlide(currentIndex - 1, true);
            }
        };

        track.addEventListener('transitionstart', () => { isTransitioning = true; });
        track.addEventListener('transitionend', () => {
            isTransitioning = false;
            if (currentIndex >= totalSlides) {
                goToSlide(0, false);
            }
        });

        const stopAutoplay = () => {
            if (autoplayTimer !== null) {
                clearInterval(autoplayTimer);
                autoplayTimer = null;
            }
        };

        const startAutoplay = () => {
            stopAutoplay();
            autoplayTimer = setInterval(nextSlide, slideDuration);
        };

        nextBtn?.addEventListener('click', () => { nextSlide(); startAutoplay(); });
        prevBtn?.addEventListener('click', () => { prevSlide(); startAutoplay(); });

        dots.forEach((dot, index) => {
            dot.addEventListener('click', () => {
                goToSlide(index, true);
                startAutoplay();
            });
        });

        sliderContainer.addEventListener('mouseenter', stopAutoplay);
        sliderContainer.addEventListener('mouseleave', startAutoplay);

        window.addEventListener('resize', () => goToSlide(currentIndex, false));

        goToSlide(0, false);
        startAutoplay();
    }

